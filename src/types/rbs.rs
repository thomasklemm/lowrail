use super::*;
use std::fmt::Write as _;

pub(super) fn signature(sig: &Signature) -> String {
    let mut params = Vec::new();
    let mut block = false;
    for p in &sig.parameters {
        let t = &p.ty.name;
        params.push(match p.kind.as_str() {
            "req" => t.clone(),
            "opt" => format!("?{t}"),
            "rest" => format!("*{t}"),
            "keyreq" => format!("{}: {t}", p.name),
            "key" => format!("?{}: {t}", p.name),
            "keyrest" => format!("**{t}"),
            "nokey" => "**nil".into(),
            "block" => {
                block = true;
                continue;
            }
            _ => continue,
        });
    }
    format!(
        "({}){} -> {}",
        params.join(", "),
        if block {
            " ?{ (*untyped) -> untyped }"
        } else {
            ""
        },
        sig.return_type.name
    )
}

#[derive(Default)]
struct Declaration<'a> {
    kind: &'static str,
    children: BTreeMap<String, Declaration<'a>>,
    methods: Vec<&'a Signature>,
}

impl<'a> Declaration<'a> {
    fn at(&mut self, name: &str) -> &mut Self {
        name.split("::").fold(self, |node, part| {
            node.children.entry(part.into()).or_default()
        })
    }

    fn render(&self, out: &mut String, indent: &str) {
        for (name, node) in &self.children {
            let kind = if node.kind.is_empty() {
                "module"
            } else {
                node.kind
            };
            let _ = writeln!(out, "{indent}{kind} {name}");
            for sig in &node.methods {
                let _ = writeln!(
                    out,
                    "{indent}  # {}",
                    sig.return_type
                        .provenance
                        .iter()
                        .map(|p| format!("{:?}: {}", p.source, p.detail.replace(['\n', '\r'], " ")))
                        .collect::<Vec<_>>()
                        .join("; ")
                );
                let _ = writeln!(
                    out,
                    "{indent}  def {}{}: {}",
                    if sig.singleton { "self." } else { "" },
                    sig.method,
                    sig.signature()
                );
            }
            node.render(out, &format!("{indent}  "));
            let _ = writeln!(out, "{indent}end");
        }
    }
}

pub(super) fn write(model: &TypeModel, facts: &Facts, out: &Path) -> Result<(), String> {
    let mut root = Declaration::default();
    for record in &facts.models {
        root.at(&record.name).kind = "class";
        for assoc in &record.associations {
            if let Some(target) = &assoc.class_name {
                root.at(target).kind = "class";
            }
        }
    }
    for controller in &facts.controllers {
        root.at(&controller.name).kind = "class";
    }
    for sig in model.methods.values() {
        // RBS can merge these with a user's signatures without declaring a
        // potentially different superclass. Facts still drive all members.
        root.at(&sig.receiver).methods.push(sig);
    }
    for module in &facts.modules {
        if model.methods.values().any(|s| s.receiver == module.name) {
            root.at(&module.name).kind = if module.kind == "class" {
                "class"
            } else {
                "module"
            };
        }
    }
    let mut app = String::from("# Generated by lowrail types; advisory, not runtime guards.\n");
    root.render(&mut app, "");
    std::fs::create_dir_all(out).map_err(|e| e.to_string())?;
    std::fs::write(out.join("app.rbs"), app).map_err(|e| e.to_string())?;
    // Minimal declarations for standalone validation, not a replacement for
    // Rails signatures. Keep this separate when using a Rails RBS collection.
    std::fs::write(out.join("lowrail_support.rbs"), "# Omit when loading full Rails signatures.\nclass BigDecimal < Numeric\nend\nclass Date\nend\nmodule ActiveSupport\n  class TimeWithZone\n  end\nend\nmodule ActiveRecord\n  class Relation[Elem]\n  end\n  module Associations\n    class CollectionProxy[Elem] < Relation[Elem]\n    end\n  end\nend\n").map_err(|e| e.to_string())?;
    Ok(())
}
