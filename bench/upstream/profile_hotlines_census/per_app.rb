# frozen_string_literal: true

# ruby bench/upstream/profile_hotlines_census/per_app.rb [N] > bench/upstream/profile_hotlines_census/per-app.md
# The top N (default 10) gem and Rails lines per app from each capture's report.json.gz, with
# script/profile-hotlines' share (objects per request on the line over the app's objects per request; per job for
# an app without requests) and reach (share of requests that run it). Dev/test-mode rows are left out, as there.
require "json"
require "zlib"

dir = __dir__
top = Integer(ARGV.fetch(0, "10"))
mean = ->(a) { a.compact.sum.fdiv([a.compact.size, 1].max) }
apps = File.readlines(File.join(dir, "apps.txt"), chomp: true).grep_v(/\A#|\A\s*\z/).map { _1.split("=", 2).first }
puts "# Top #{top} gem and Rails lines per app\n\n"
puts "Generated by [per_app.rb](per_app.rb) from each app's `profiled/report.json.gz`. Share: the line's objects per " \
     "request over the app's objects per request (both runs' mean). Reach: the share of requests that run it. " \
     "Dev/test-mode work is left out. Cross-app ranking: [the record](../../../docs/upstream/profile-hotlines-census-2026-11-26.md).\n\n"
apps.each do |app|
  j = JSON.parse(Zlib::GzipReader.open(File.join(dir, app, "profiled/report.json.gz"), &:read))
  per = mean.(j["summary"].map { _1["objects_per_request"] })
  units = mean.(j["summary"].map { _1.dig("completed", "request") })
  rows = j.fetch("rows", []).to_h { [_1["site"], _1] }
  lines = j["ranked"].filter_map do |r|
    next if r["mode"] || !r["group"].to_s.match?(/\A(gem|rails): /)
    [r["site"], mean.(r["all"]) / per, mean.(r["reached"]) / units]
  end.sort_by { -_2 }.first(top)
  puts "## #{app}\n\n#{units.round} requests per run, #{per.round} objects per request.\n\n"
  puts "| # | Line | Method | Code | Share | Reach |\n| ---: | --- | --- | --- | ---: | ---: |"
  lines.each_with_index do |(site, share, reach), i|
    row = rows[site] || {}
    code = row["text"].to_s[0, 60].gsub("|", "\\|").gsub("`", "'")
    puts "| #{i + 1} | `#{site.sub(%r{\A(GEM|RAILS)/}, '')}` | `#{row['method']}` | #{code.empty? ? '' : "`#{code}`"} | #{format('%.2f%%', 100 * share)} | #{format('%.0f%%', 100 * reach)} |"
  end
  puts
end
