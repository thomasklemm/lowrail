# frozen_string_literal: true

# Static research inventory, not a count of live methods or request calls.
# ruby rails_codegen_inventory.rb RAILS_CHECKOUT > inventory.json
# ruby rails_codegen_inventory.rb RAILS_CHECKOUT --table > inventory.md
require "json"
require "prism"
require "digest"

root = File.realpath(ARGV.fetch(0))
revision = IO.popen(["git", "-C", root, "rev-parse", "HEAD"], &:read).strip
abort "Rails checkout required" unless $?.success?
emitters = %i[define_method define_singleton_method redefine_method redefine_singleton_method
  define_cached_method class_eval module_eval instance_eval instance_exec class_exec module_exec eval]
native = %i[attr_reader attr_writer attr_accessor attr_internal attr_internal_reader attr_internal_writer
  attr_internal_accessor alias_method]
dispatch = %i[send public_send __send__]
sites, errors, hashes = [], [], {}
files = Dir["#{root}/*/{lib,app}/**/*.rb"].reject { _1.include?("/templates/") }.sort
files.each do |file|
  parsed = Prism.parse_file(file)
  relative = file.delete_prefix(root + "/")
  hashes[relative] = Digest::SHA256.file(file).hexdigest
  errors.concat(parsed.errors.map { [relative, _1.location.start_line, _1.message] })
  visit = lambda do |node, enclosing|
    enclosing = node.name.to_s if Prism::DefNode === node
    if Prism::CallNode === node && (emitters.include?(node.name) || native.include?(node.name) ||
        dispatch.include?(node.name) || node.name == :batch && node.receiver&.location&.slice&.include?("CodeGenerator"))
      kind = if native.include?(node.name)
        "native_or_alias"
      elsif dispatch.include?(node.name)
        "dispatch_call"
      else
        "emitter_or_exec"
      end
      source = node.location.slice
      sites << { file: relative, line: node.location.start_line, end_line: node.location.end_line,
        kind: kind, call: node.name, receiver: node.receiver&.location&.slice,
        enclosing: enclosing, arguments: node.arguments&.location&.slice,
        block: node.block&.class&.name&.delete_prefix("Prism::"),
        dispatch_in_source: source.scan(/\b(?:public_send|__send__|send)\b/).uniq,
        source: source }
    elsif Prism::DefNode === node && %i[method_missing respond_to_missing?].include?(node.name)
      sites << { file: relative, line: node.location.start_line, end_line: node.location.end_line,
        kind: "dynamic_dispatch", call: node.name, enclosing: enclosing, source: node.location.slice }
    end
    node.compact_child_nodes.each { visit.call(_1, enclosing) }
  end
  visit.call(parsed.value, nil)
end
abort errors.inspect unless errors.empty?

if ARGV.include?("--table")
  puts "# Rails runtime-generation inventory appendix"
  puts
  puts "Generated by `bench/experiments/rails_codegen_inventory.rb --table`; see [survey](rails-codegen-survey.md) for scope, interpretation and verdicts."
  puts
  puts "Source revision: [#{revision[0, 12]}](https://github.com/rails/rails/commit/#{revision})."
  puts
  puts "This is an exhaustive **syntactic API index within the stated scope**, not an assertion that every eval defines methods. Native attributes/aliases and direct dispatch calls are counted separately below. `send in source` is lexical: it also sees generated string bodies, but does not prove they execute. The JSON mode retains full sources and every direct dispatch call for follow-up."
  puts
  puts "| File | APIs and line numbers | send in source |"
  puts "|---|---|---|"
  sites.reject { %w[native_or_alias dispatch_call].include?(_1[:kind]) }.group_by { _1[:file] }.each do |file, rows|
    references = rows.map do |row|
      "[`#{row[:call]}:#{row[:line]}`](https://github.com/rails/rails/blob/#{revision}/#{file}#L#{row[:line]})"
    end
    sends = rows.select { !_1.fetch(:dispatch_in_source, []).empty? }.map { _1[:line] }
    puts "| `#{file}` | #{references.join(', ')} | #{sends.empty? ? '—' : sends.join(', ')} |"
  end
  puts
  puts "Files parsed: #{files.size}; parse errors: #{errors.size}."
  puts
  sites.group_by { _1[:kind] }.each { |kind, rows| puts "- #{kind}: #{rows.size}" }
else
  puts JSON.pretty_generate(rails_revision: revision,
    files: files.size, source_sha256: hashes, errors: errors, sites: sites)
end
